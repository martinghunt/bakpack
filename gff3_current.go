// GFF3 in the style of Bakta >= 1.10. Bakta 1.10.0 changed how it writes
// GFF3, so JSON from those versions is rendered by this port of Bakta's
// bakta/io/gff.py (unchanged in output from 1.10.0 to 1.12.2), which also
// supports Bakta's --compliant (INSDC) mode. Older JSON keeps the original
// renderer in gff3.go. Attribute values follow Python's str(), and attributes
// keep Python dict insertion order, so the output matches Bakta byte for byte.

var baktaVersionPattern = regexp.MustCompile(`^v?(\d+)\.(\d+)`)

// usesCurrentBaktaGFF3Style reports whether data comes from Bakta >= 1.10,
// judged by its recorded Bakta version, or by its JSON layout when the
// version is missing or unreadable.
func usesCurrentBaktaGFF3Style(data map[string]any) bool {
	version, _ := data["version"].(map[string]any)
	baktaVersion, _ := version["bakta"].(string)
	if m := baktaVersionPattern.FindStringSubmatch(baktaVersion); m != nil {
		major, _ := strconv.Atoi(m[1])
		minor, _ := strconv.Atoi(m[2])
		return major > 1 || (major == 1 && minor >= 10)
	}
	return usesCurrentBaktaLayout(data)
}

const (
	baktaCDSSourceUser = "user-provided"
	baktaDBXrefRFAM    = "RFAM"
	baktaDBXrefEC      = "EC"
)

// baktaINSDCValidDBXrefs are the Dbxref prefixes Bakta keeps in compliant
// mode; others become Notes.
var baktaINSDCValidDBXrefs = map[string]bool{"UniProtKB/TrEMBL": true, "GO": true, "Pfam": true, "RFAM": true}

// baktaGeneSymbolPattern is Bakta's RE_GENE_SYMBOL, used with fullmatch.
var baktaGeneSymbolPattern = regexp.MustCompile(`^[a-z]{3}[A-Z][0-9]?$`)

func writeCurrentBaktaGFF3(data map[string]any, opts BaktaGFF3Options) ([]byte, error) {
	compliant := opts.Compliant
	var buf bytes.Buffer
	buf.WriteString("##gff-version 3\n")
	buf.WriteString("##feature-ontology https://github.com/The-Sequence-Ontology/SO-Ontologies/blob/v3.1/so.obo\n")
	fmt.Fprintf(&buf, "# Generated by bakpack %s\n", opts.bakpackVersion())
	genome, _ := data["genome"].(map[string]any)
	if taxon := genome["taxon"]; pyTruthy(taxon) {
		fmt.Fprintf(&buf, "# organism %s\n", pyStr(taxon))
	}
	buf.WriteString("# Annotated with Bakta\n")
	// Bakta always records its versions; skip the lines for JSON that does not.
	version, _ := data["version"].(map[string]any)
	if baktaVersion, ok := version["bakta"]; ok {
		fmt.Fprintf(&buf, "# Software: v%s\n", pyStr(baktaVersion))
	}
	if db, ok := version["db"].(map[string]any); ok {
		dbVersion := pyStr(db["version"])
		if parts := strings.Split(dbVersion, "."); len(parts) >= 2 {
			dbVersion = parts[0] + "." + parts[1]
		}
		fmt.Fprintf(&buf, "# Database: v%s, %s\n", dbVersion, pyStr(db["type"]))
	}
	buf.WriteString("# DOI: 10.1099/mgen.0.000685\n")
	buf.WriteString("# URL: github.com/oschwengers/bakta\n")

	featuresBySequence, featureOrder := gffFeaturesByContig(data)
	sequences := mapSlice(data["sequences"])
	written := map[string]bool{}
	for _, seq := range sequences {
		id := pyStr(seq["id"])
		written[id] = true
		length := seq["length"]
		fmt.Fprintf(&buf, "##sequence-region %s 1 %s\n", id, pyStr(length))
		region := newPyAttrs()
		region.set("ID", seq["id"])
		region.set("Name", seq["id"])
		if seq["topology"] == "circular" {
			region.set("Is_circular", "true")
		}
		fmt.Fprintf(&buf, "%s\tBakta\tregion\t1\t%s\t.\t+\t.\t%s\n", id, pyStr(length), region.encode())
		seqLength, _ := jsonInt(length)
		for _, feature := range featuresBySequence[id] {
			if err := writeCurrentBaktaGFF3Feature(&buf, feature, seqLength, compliant); err != nil {
				return nil, err
			}
		}
	}
	// Bakta cannot write features on unlisted sequences; keep them rather
	// than drop them.
	for _, id := range featureOrder {
		if written[id] {
			continue
		}
		for _, feature := range featuresBySequence[id] {
			if err := writeCurrentBaktaGFF3Feature(&buf, feature, 0, compliant); err != nil {
				return nil, err
			}
		}
	}

	if !compliant && !opts.AnnotationOnly {
		buf.WriteString("##FASTA\n")
		ntKey := sequenceNTKey(usesCurrentBaktaLayout(data))
		for _, seq := range sequences {
			fmt.Fprintf(&buf, ">%s\n", pyStr(seq["id"]))
			nt, _ := seq[ntKey].(string)
			for i := 0; i < len(nt); i += 60 {
				end := min(i+60, len(nt))
				buf.WriteString(nt[i:end])
				buf.WriteByte('\n')
			}
			if nt == "" {
				buf.WriteByte('\n')
			}
		}
	}
	return buf.Bytes(), nil
}

func writeCurrentBaktaGFF3Feature(buf *bytes.Buffer, feat map[string]any, seqLength int, compliant bool) error {
	featureType, _ := feat["type"].(string)
	if _, ok := baktaFeatureType(featureType); !ok {
		return unsupportedBaktaFeatureTypeError(featureType)
	}
	seqID, _ := featureContig(feat)
	start, startOK := jsonInt(feat["start"])
	stop, stopOK := jsonInt(feat["stop"])
	if seqID == "" || !startOK || !stopOK {
		return fmt.Errorf("feature %s is missing contig, start, or stop", gffFeatureID(feat))
	}
	if _, edge := feat["edge"]; edge {
		stop += seqLength
	}
	strand := pyStr(feat["strand"])
	_, truncated := feat["truncated"]
	_, pseudogene := feat["pseudogene"]
	locus := pyStr(feat["locus"])
	line := func(source, gffType, score, phase string, attrs *pyAttrs) {
		fmt.Fprintf(buf, "%s\t%s\t%s\t%d\t%d\t%s\t%s\t%s\t%s\n", seqID, source, gffType, start, stop, score, strand, phase, attrs.encode())
	}
	geneLine := func(source string, attrs *pyAttrs) {
		line(source, "gene", ".", ".", attrs)
	}
	reviseDBXrefs := func(attrs *pyAttrs) {
		valid, invalid := reviseDBXrefsINSDC(feat["db_xrefs"])
		attrs.set("Dbxref", valid)
		attrs.set("Note", invalid)
	}
	rfamInference := func(attrs *pyAttrs) {
		for _, dbxref := range pyList(feat["db_xrefs"]) {
			parts := strings.Split(pyStr(dbxref), ":")
			if parts[0] == baktaDBXrefRFAM && len(parts) > 1 {
				attrs.set("inference", "profile:Rfam:"+parts[1])
			}
		}
	}

	switch featureType {
	case "tRNA":
		attrs := newPyAttrs()
		attrs.set("ID", feat["locus"])
		attrs.set("Name", feat["product"])
		attrs.set("locus_tag", feat["locus"])
		attrs.set("product", feat["product"])
		attrs.set("Dbxref", feat["db_xrefs"])
		if pyTruthy(feat["gene"]) {
			attrs.set("gene", feat["gene"])
		}
		if pseudogene {
			attrs.set("pseudogene", "unknown")
		} else if truncated {
			attrs.set("pseudo", true)
		}
		if pyTruthy(feat["anti_codon"]) {
			attrs.set("anti_codon", feat["anti_codon"])
		}
		if pyTruthy(feat["amino_acid"]) {
			attrs.set("amino_acid", feat["amino_acid"])
		}
		if compliant {
			geneID := locus + "_gene"
			attrs.set("Parent", geneID)
			attrs.set("inference", "profile:tRNAscan:2.0")
			reviseDBXrefs(attrs)
			gene := newPyAttrs()
			gene.set("ID", geneID)
			gene.set("locus_tag", feat["locus"])
			if pyTruthy(feat["gene"]) {
				gene.set("gene", feat["gene"])
			}
			if pseudogene {
				gene.set("pseudogene", "unknown")
			}
			geneLine("tRNAscan-SE", gene)
		}
		line("tRNAscan-SE", "tRNA", ".", ".", attrs)

	case "tmRNA":
		attrs := newPyAttrs()
		attrs.set("ID", feat["locus"])
		attrs.set("Name", feat["product"])
		attrs.set("locus_tag", feat["locus"])
		attrs.set("gene", feat["gene"])
		attrs.set("product", feat["product"])
		attrs.set("Dbxref", feat["db_xrefs"])
		tag, hasTag := feat["tag"].(map[string]any)
		if hasTag {
			attrs.set("tag_peptide", tag["aa"])
		}
		if truncated {
			attrs.set("pseudo", true)
		}
		if compliant {
			geneID := locus + "_gene"
			attrs.set("Parent", geneID)
			attrs.set("inference", "profile:aragorn:1.2")
			reviseDBXrefs(attrs)
			if hasTag {
				location := pyStr(tag["start"]) + ".." + pyStr(tag["stop"])
				if feat["strand"] != "+" {
					location = "complement(" + location + ")"
				}
				attrs.set("tag_peptide", location)
			}
			gene := newPyAttrs()
			gene.set("ID", geneID)
			gene.set("locus_tag", feat["locus"])
			gene.set("gene", feat["gene"])
			if truncated {
				gene.set("pseudo", true)
			}
			geneLine("Aragorn", gene)
		}
		line("Aragorn", "tmRNA", ".", ".", attrs)

	case "rRNA":
		attrs := newPyAttrs()
		attrs.set("ID", feat["locus"])
		attrs.set("Name", feat["product"])
		attrs.set("locus_tag", feat["locus"])
		attrs.set("gene", feat["gene"])
		attrs.set("product", feat["product"])
		attrs.set("Dbxref", feat["db_xrefs"])
		if truncated {
			attrs.set("pseudo", true)
		}
		if compliant {
			geneID := locus + "_gene"
			attrs.set("Parent", geneID)
			reviseDBXrefs(attrs)
			rfamInference(attrs)
			gene := newPyAttrs()
			gene.set("ID", geneID)
			gene.set("locus_tag", feat["locus"])
			gene.set("gene", feat["gene"])
			if truncated {
				gene.set("pseudo", true)
			}
			geneLine("Infernal", gene)
		}
		line("Infernal", "rRNA", pyStr(feat["evalue"]), ".", attrs)

	case "ncRNA":
		attrs := newPyAttrs()
		attrs.set("ID", feat["locus"])
		attrs.set("Name", feat["product"])
		attrs.set("locus_tag", feat["locus"])
		attrs.set("gene", feat["gene"])
		attrs.set("product", feat["product"])
		attrs.set("Dbxref", feat["db_xrefs"])
		if truncated {
			attrs.set("pseudo", true)
		}
		if compliant {
			geneID := locus + "_gene"
			attrs.set("Parent", geneID)
			reviseDBXrefs(attrs)
			attrs.set("ncRNA_class", selectNCRNAClass(feat["class"]))
			rfamInference(attrs)
			// Bakta drops a non-standard gene symbol from the ncRNA but
			// keeps it on the gene line.
			gene := newPyAttrs()
			gene.set("ID", geneID)
			gene.set("locus_tag", feat["locus"])
			gene.set("gene", feat["gene"])
			if symbol, _ := feat["gene"].(string); !baktaGeneSymbolPattern.MatchString(symbol) {
				attrs.remove("gene")
			}
			if truncated {
				gene.set("pseudo", true)
			}
			geneLine("Infernal", gene)
		}
		line("Infernal", "ncRNA", pyStr(feat["evalue"]), ".", attrs)

	case "ncRNA-region":
		attrs := newPyAttrs()
		attrs.set("ID", feat["id"])
		attrs.set("Name", feat["product"])
		attrs.set("product", feat["product"])
		attrs.set("Dbxref", feat["db_xrefs"])
		if truncated {
			attrs.set("pseudo", true)
		}
		if compliant {
			rfamInference(attrs)
			reviseDBXrefs(attrs)
			attrs.set("regulatory_class", selectRegulatoryClass(feat["class"]))
		}
		line("Infernal", "regulatory_region", pyStr(feat["evalue"]), ".", attrs)

	case "crispr":
		attrs := newPyAttrs()
		attrs.set("ID", feat["id"])
		attrs.set("Name", feat["product"])
		attrs.set("product", feat["product"])
		gffType := "CRISPR"
		if compliant {
			gffType = "repeat_region"
			attrs.set("inference", "COORDINATES:alignment:pilercr:1.02")
			reviseDBXrefs(attrs)
			attrs.set("rpt_family", "CRISPR")
			attrs.set("rpt_type", "direct")
			attrs.set("rpt_unit_seq", feat["repeat_consensus"])
		}
		line("PILER-CR", gffType, ".", ".", attrs)
		if !compliant {
			writeCurrentCRISPRChildren(buf, seqID, feat)
		}

	case "cds":
		attrs := newPyAttrs()
		attrs.set("ID", feat["locus"])
		attrs.set("Name", feat["product"])
		attrs.set("locus_tag", feat["locus"])
		attrs.set("product", feat["product"])
		attrs.set("Dbxref", feat["db_xrefs"])
		pseudogeneType := ""
		if pseudogene {
			pseudogeneType = "unitary"
			if info, _ := feat["pseudogene"].(map[string]any); pyTruthy(info["paralog"]) {
				pseudogeneType = "unprocessed"
			}
			attrs.set("pseudogene", pseudogeneType)
		} else if truncated {
			attrs.set("pseudo", true)
		}
		if pyTruthy(feat["gene"]) {
			attrs.set("gene", feat["gene"])
		}
		userProvided := feat["source"] == baktaCDSSourceUser
		source := "Pyrodigal"
		if userProvided {
			source = "?"
		}
		if compliant {
			geneID := locus + "_gene"
			attrs.set("Parent", geneID)
			if userProvided {
				attrs.set("inference", "EXISTENCE:non-experimental evidence, no additional details recorded")
			} else {
				attrs.set("inference", "ab initio prediction:Pyrodigal:3.5")
			}
			reviseDBXrefs(attrs)
			moveECNumber(attrs)
			gene := newPyAttrs()
			gene.set("ID", geneID)
			gene.set("locus_tag", feat["locus"])
			if pyTruthy(feat["gene"]) {
				gene.set("gene", feat["gene"])
			}
			if pseudogene {
				gene.set("pseudogene", pseudogeneType)
			}
			geneLine(source, gene)
		}
		if exception, ok := feat["exception"].(map[string]any); ok {
			switch exception["type"] {
			case "selenocysteine":
				position := pyStr(exception["start"]) + ".." + pyStr(exception["stop"])
				if feat["strand"] == "-" {
					position = "complement(" + position + ")"
				}
				attrs.set("transl_except", "(pos:"+position+",aa:"+pyStr(exception["aa"])+")")
				notes, _ := attrs.get("Note")
				attrs.set("Note", append(pyList(notes), fmt.Sprintf("codon on position %s is a %s codon", pyStr(exception["codon_position"]), pyStr(exception["type"]))))
			case "ribosomal_slippage":
				attrs.set("ribosomal_slippage", true)
			}
		}
		line(source, "CDS", ".", "0", attrs)
		writeCurrentSignalPeptide(buf, seqID, feat)

	case "sorf":
		attrs := newPyAttrs()
		attrs.set("ID", feat["locus"])
		attrs.set("Name", feat["product"])
		attrs.set("locus_tag", feat["locus"])
		attrs.set("product", feat["product"])
		attrs.set("Dbxref", feat["db_xrefs"])
		if pyTruthy(feat["gene"]) {
			attrs.set("gene", feat["gene"])
		}
		if compliant {
			geneID := locus + "_gene"
			attrs.set("Parent", geneID)
			reviseDBXrefs(attrs)
			moveECNumber(attrs)
			gene := newPyAttrs()
			gene.set("ID", geneID)
			gene.set("locus_tag", feat["locus"])
			gene.set("inference", "ab initio prediction:Bakta")
			if pyTruthy(feat["gene"]) {
				gene.set("gene", feat["gene"])
			}
			geneLine("Bakta", gene)
		}
		line("Bakta", "CDS", ".", "0", attrs)
		writeCurrentSignalPeptide(buf, seqID, feat)

	case "gap":
		attrs := newPyAttrs()
		attrs.set("ID", feat["id"])
		attrs.set("Name", "gap ("+pyStr(feat["length"])+" bp)")
		attrs.set("product", "gap ("+pyStr(feat["length"])+" bp)")
		line("Bakta", "gap", ".", ".", attrs)

	case "oriC", "oriV", "oriT":
		attrs := newPyAttrs()
		attrs.set("ID", feat["id"])
		attrs.set("Name", feat["product"])
		if compliant {
			attrs.set("Note", feat["product"])
		} else {
			attrs.set("product", feat["product"])
			attrs.set("inference", "similar to DNA sequence")
		}
		gffType := "oriC"
		switch {
		case featureType == "oriT":
			gffType = "oriT"
		case compliant:
			gffType = "rep_origin"
		}
		line("BLAST+", gffType, ".", ".", attrs)

	default:
		return unsupportedBaktaFeatureTypeError(featureType)
	}
	return nil
}

func writeCurrentCRISPRChildren(buf *bytes.Buffer, seqID string, feat map[string]any) {
	id := pyStr(feat["id"])
	repeats := mapSlice(feat["repeats"])
	spacers := mapSlice(feat["spacers"])
	child := func(gffType string, region map[string]any, attrs *pyAttrs) {
		fmt.Fprintf(buf, "%s\tPILER-CR\t%s\t%s\t%s\t.\t%s\t.\t%s\n", seqID, gffType, pyStr(region["start"]), pyStr(region["stop"]), pyStr(region["strand"]), attrs.encode())
	}
	i := 0
	for ; i < len(spacers) && i < len(repeats); i++ {
		repeat := newPyAttrs()
		repeat.set("ID", fmt.Sprintf("%s_repeat_%d", id, i+1))
		repeat.set("Parent", feat["id"])
		child("crispr-repeat", repeats[i], repeat)
		spacer := newPyAttrs()
		spacer.set("ID", fmt.Sprintf("%s_spacer_%d", id, i+1))
		spacer.set("Parent", feat["id"])
		spacer.set("sequence", spacers[i]["sequence"])
		child("crispr-spacer", spacers[i], spacer)
	}
	// Bakta writes the final repeat without a Parent.
	if len(repeats)-1 == i {
		repeat := newPyAttrs()
		repeat.set("ID", fmt.Sprintf("%s_repeat_%d", id, i+1))
		child("crispr-repeat", repeats[i], repeat)
	}
}

func writeCurrentSignalPeptide(buf *bytes.Buffer, seqID string, feat map[string]any) {
	peptide, ok := feat["signal-peptide"].(map[string]any)
	if !ok {
		return
	}
	attrs := newPyAttrs()
	attrs.set("ID", pyStr(feat["locus"])+"_sigpep")
	attrs.set("Name", "signal peptide")
	attrs.set("product", "signal peptide")
	attrs.set("score", peptide["score"])
	attrs.set("Parent", feat["locus"])
	score, _ := jsonFloat(peptide["score"])
	fmt.Fprintf(buf, "%s\tDeepSig\tsignal_peptide\t%s\t%s\t%s\t%s\t.\t%s\n", seqID, pyStr(peptide["start"]), pyStr(peptide["stop"]), strconv.FormatFloat(score, 'f', 2, 64), pyStr(feat["strand"]), attrs.encode())
}

// reviseDBXrefsINSDC splits Dbxrefs into those valid for INSDC and the rest,
// as Bakta's revise_dbxref_insdc does.
func reviseDBXrefsINSDC(dbxrefs any) ([]any, []any) {
	valid, invalid := []any{}, []any{}
	for _, dbxref := range pyList(dbxrefs) {
		if baktaINSDCValidDBXrefs[strings.Split(pyStr(dbxref), ":")[0]] {
			valid = append(valid, dbxref)
		} else {
			invalid = append(invalid, dbxref)
		}
	}
	return valid, invalid
}

// moveECNumber moves the last EC Note into an ec_number attribute, as
// Bakta's extract_ec_from_notes_insdc does.
func moveECNumber(attrs *pyAttrs) {
	notes, _ := attrs.get("Note")
	kept := []any{}
	var ecNumber any
	for _, note := range pyList(notes) {
		if strings.Split(pyStr(note), ":")[0] == baktaDBXrefEC {
			ecNumber = strings.ReplaceAll(pyStr(note), "EC:", "")
		} else {
			kept = append(kept, note)
		}
	}
	attrs.set("Note", kept)
	if ecNumber != nil {
		attrs.set("ec_number", ecNumber)
	}
}

// soClassID returns the SO ID of a Bakta feature class, stored in JSON as
// [name, id].
func soClassID(class any) (string, bool) {
	parts := pyList(class)
	if len(parts) < 2 {
		return "", false
	}
	return pyStr(parts[1]), true
}

func selectNCRNAClass(class any) string {
	id, _ := soClassID(class)
	switch id {
	case "SO:0000644":
		return "antisense_RNA"
	case "SO:0000374":
		return "ribozyme"
	case "SO:0000386":
		return "RNase_P_RNA"
	default:
		return "other"
	}
}

func selectRegulatoryClass(class any) string {
	id, _ := soClassID(class)
	switch id {
	case "SO:0000140":
		return "attenuator"
	case "SO:0000035":
		return "riboswitch"
	case "SO:0002168":
		return "response_element"
	case "SO:1001268", "SO:0001427":
		return "recoding_stimulatory_region"
	case "SO:0000139":
		return "ribosome_binding_site"
	default:
		return "other"
	}
}

// pyAttrs is an ordered attribute map with Python dict semantics: setting an
// existing key keeps its position.
type pyAttrs struct {
	keys   []string
	values map[string]any
}

func newPyAttrs() *pyAttrs {
	return &pyAttrs{values: map[string]any{}}
}

func (a *pyAttrs) set(key string, value any) {
	if _, exists := a.values[key]; !exists {
		a.keys = append(a.keys, key)
	}
	a.values[key] = value
}

func (a *pyAttrs) get(key string) (any, bool) {
	value, ok := a.values[key]
	return value, ok
}

func (a *pyAttrs) remove(key string) {
	if _, exists := a.values[key]; !exists {
		return
	}
	delete(a.values, key)
	keys := a.keys[:0]
	for _, k := range a.keys {
		if k != key {
			keys = append(keys, k)
		}
	}
	a.keys = keys
}

// encode joins the attributes as Bakta's encode_annotations does: lists are
// comma-joined and omitted when empty; other values use Python's str().
func (a *pyAttrs) encode() string {
	parts := make([]string, 0, len(a.keys))
	for _, key := range a.keys {
		value := a.values[key]
		if list, ok := value.([]any); ok {
			if len(list) == 0 {
				continue
			}
			encoded := make([]string, len(list))
			for i, item := range list {
				encoded[i] = baktaEncodeAttribute(pyStr(item))
			}
			parts = append(parts, key+"="+strings.Join(encoded, ","))
			continue
		}
		parts = append(parts, key+"="+baktaEncodeAttribute(pyStr(value)))
	}
	return strings.Join(parts, ";")
}

// baktaEncodeAttribute escapes the characters Bakta's encode_attribute does.
func baktaEncodeAttribute(value string) string {
	return strings.NewReplacer("%", "%25", ";", "%3B", "=", "%3D", "&", "%26", ",", "%2C").Replace(value)
}

func pyList(value any) []any {
	list, _ := value.([]any)
	return list
}

// pyTruthy follows Python truthiness for decoded JSON values.
func pyTruthy(value any) bool {
	switch v := value.(type) {
	case nil:
		return false
	case bool:
		return v
	case string:
		return v != ""
	case json.Number:
		f, err := v.Float64()
		return err != nil || f != 0
	case []any:
		return len(v) > 0
	case map[string]any:
		return len(v) > 0
	default:
		return true
	}
}

// pyStr formats a decoded JSON value as Python's str() would after
// json.load.
func pyStr(value any) string {
	switch v := value.(type) {
	case nil:
		return "None"
	case bool:
		if v {
			return "True"
		}
		return "False"
	case string:
		return v
	case json.Number:
		literal := v.String()
		if !strings.ContainsAny(literal, ".eE") {
			if i, err := strconv.ParseInt(literal, 10, 64); err == nil {
				return strconv.FormatInt(i, 10)
			}
			return literal
		}
		f, err := v.Float64()
		if err != nil {
			return literal
		}
		return pyFloatRepr(f)
	case int:
		return strconv.Itoa(v)
	case int64:
		return strconv.FormatInt(v, 10)
	case float64:
		return pyFloatRepr(v)
	default:
		return fmt.Sprint(v)
	}
}

// pyFloatRepr formats f as Python's repr(float): the shortest round-trip
// digits, in fixed notation for decimal exponents from -4 to 15 and in
// scientific notation with at least two exponent digits otherwise.
func pyFloatRepr(f float64) string {
	switch {
	case math.IsInf(f, 1):
		return "inf"
	case math.IsInf(f, -1):
		return "-inf"
	case math.IsNaN(f):
		return "nan"
	}
	sci := strconv.FormatFloat(f, 'e', -1, 64) // e.g. -1.2345e-05
	mantissa, expText, _ := strings.Cut(sci, "e")
	exp, _ := strconv.Atoi(expText)
	sign := ""
	if strings.HasPrefix(mantissa, "-") {
		sign, mantissa = "-", mantissa[1:]
	}
	digits := strings.Replace(mantissa, ".", "", 1)
	if exp < -4 || exp >= 16 {
		out := digits[:1]
		if len(digits) > 1 {
			out += "." + digits[1:]
		}
		expSign := "+"
		if exp < 0 {
			expSign, exp = "-", -exp
		}
		return fmt.Sprintf("%s%se%s%02d", sign, out, expSign, exp)
	}
	point := exp + 1 // digits before the decimal point
	switch {
	case point <= 0:
		return sign + "0." + strings.Repeat("0", -point) + digits
	case point >= len(digits):
		return sign + digits + strings.Repeat("0", point-len(digits)) + ".0"
	default:
		return sign + digits[:point] + "." + digits[point:]
	}
}
